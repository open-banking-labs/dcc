-- System announcements ("系统公告"): the banner the console shows to every signed-in user.
--
-- Two authors, two scopes, one table:
--   * tenant_id IS NULL     platform announcement, authored by the system administrator, shown to
--                           every tenant (maintenance windows, platform-wide notices);
--   * tenant_id IS NOT NULL tenant announcement, authored by that tenant's administrator, shown to
--                           that tenant only.
--
-- Deliberately NOT a TenantScopedEntity: the platform rows must be readable by every tenant, so
-- the Hibernate tenantFilter (which would hide them) is not applied here. Isolation lives in the
-- explicit `tenant_id is null or tenant_id = :tenantId` predicate in the repository, exactly like
-- `audit_log` and `role_assignment`. Retention columns come from BaseEntity, so removes are logical.

CREATE TABLE announcement (
    id              bigint generated by default as identity PRIMARY KEY,
    tenant_id       varchar(64),
    level           varchar(16)  NOT NULL,
    title           varchar(200) NOT NULL,
    body            varchar(2000) NOT NULL,
    enabled         boolean      NOT NULL DEFAULT true,
    starts_at       timestamp with time zone,
    ends_at         timestamp with time zone,
    created_at      timestamp with time zone NOT NULL,
    updated_at      timestamp with time zone NOT NULL,
    deleted_at      timestamp with time zone,
    deleted_by      varchar(128),
    deletion_reason varchar(512)
);

COMMENT ON TABLE announcement IS
    'System announcements shown as a console banner; tenant_id null = platform-wide';
COMMENT ON COLUMN announcement.tenant_id IS
    'Owning tenant, or null for a platform announcement visible to every tenant';
COMMENT ON COLUMN announcement.level IS
    'INFO | WARNING | MAINTENANCE (banner urgency)';
COMMENT ON COLUMN announcement.starts_at IS
    'Optional start of the visibility window; null means "visible immediately"';
COMMENT ON COLUMN announcement.ends_at IS
    'Optional end of the visibility window; null means "until disabled"';

-- the banner query is (tenant_id is null or tenant_id = ?) and enabled, so the tenant column
-- leads; the partial predicate keeps logically deleted rows out of the index
CREATE INDEX ix_announcement_visible
    ON announcement (tenant_id, enabled)
    WHERE deleted_at IS NULL;
