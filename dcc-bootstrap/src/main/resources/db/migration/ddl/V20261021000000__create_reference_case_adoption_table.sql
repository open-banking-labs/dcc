-- ADR 0005 §D7 (follow-up): adoption index for reference cases.
--
-- The version message records *that* an artifact came from a case, but a text stamp cannot answer
-- "which of my objects came from an outdated case". This table keeps the machine-readable link.
--
-- Platform-level like `role_assignment`: it carries an explicit tenant_id but is NOT tenant-filtered,
-- because the same rows are read from two sides — the tenant (my adoptions) and the platform
-- (the reach of one case, across tenants). Two side-scoped queries therefore use explicit
-- tenant predicates instead of relying on the Hibernate tenant filter.

CREATE TABLE reference_case_adoption (
    id                 bigint generated by default as identity PRIMARY KEY,
    tenant_id          varchar(64)  NOT NULL,
    case_id            bigint       NOT NULL,
    case_code          varchar(128) NOT NULL,
    case_version       varchar(32)  NOT NULL,
    artifact_type      varchar(32)  NOT NULL,
    artifact_id        bigint,
    artifact_code      varchar(128),
    adopted_by         varchar(128),
    created_at         timestamp with time zone NOT NULL,
    updated_at         timestamp with time zone NOT NULL,
    deleted_at         timestamp with time zone,
    deleted_by         varchar(128),
    deletion_reason    varchar(512)
);

COMMENT ON TABLE reference_case_adoption IS
    'Machine-readable provenance of adopted reference cases (ADR 0005); platform-level, explicit tenant_id';
COMMENT ON COLUMN reference_case_adoption.case_version IS
    'Case version at adoption time; compared with the case''s current version to flag a stale copy';
COMMENT ON COLUMN reference_case_adoption.artifact_type IS
    'DATA_STANDARD | TABLE_STRUCTURE | INTERFACE | INTERFACE_TEMPLATE | SKELETON';

CREATE INDEX ix_case_adoption_tenant ON reference_case_adoption (tenant_id, id);
CREATE INDEX ix_case_adoption_case ON reference_case_adoption (case_id, id);
