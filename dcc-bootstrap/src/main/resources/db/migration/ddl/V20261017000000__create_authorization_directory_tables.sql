-- Authorization directory: memberships and tenant-scoped role assignments, backing
-- dcc.security.directory-mode (docs/decisions/0003-authorization-directory.md).
-- Directory rows are platform-level: neither table carries tenant_id, so the
-- Hibernate tenantFilter does not apply. Retention columns are included from day
-- one because the entities extend BaseEntity.

CREATE TABLE tenant_membership (
    id          bigint generated by default as identity PRIMARY KEY,
    subject     varchar(128) NOT NULL,
    tenant_code varchar(64)  NOT NULL,
    created_at  timestamp with time zone NOT NULL,
    updated_at  timestamp with time zone NOT NULL,
    deleted_at  timestamp with time zone,
    deleted_by  varchar(128),
    deletion_reason varchar(512)
);

CREATE TABLE role_assignment (
    id          bigint generated by default as identity PRIMARY KEY,
    subject     varchar(128) NOT NULL,
    tenant_code varchar(64)  NOT NULL,
    role        varchar(64)  NOT NULL,
    created_at  timestamp with time zone NOT NULL,
    updated_at  timestamp with time zone NOT NULL,
    deleted_at  timestamp with time zone,
    deleted_by  varchar(128),
    deletion_reason varchar(512)
);
