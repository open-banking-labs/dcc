-- ADR 0005 §D8 (database-backed resolver): role -> permission points, so a deployment can re-cut its
-- roles without a redeploy. Platform-level like `role_assignment`: no tenant_id, no tenant filter.
-- Rows extend BaseEntity, so every mapping change lands in the append-only audit trail and a removed
-- mapping is a logical delete (retention) rather than a physical one.

create table role_permission (
    id              bigint generated by default as identity primary key,
    role            varchar(64) not null,
    permission      varchar(64) not null,
    created_at      timestamp with time zone not null,
    updated_at      timestamp with time zone not null,
    deleted_at      timestamp with time zone,
    deleted_by      varchar(128),
    deletion_reason varchar(512)
);

comment on table role_permission is
    'Database-backed role -> permission mappings (dcc.security.resolver-mode=database)';
comment on column role_permission.permission is
    'Permission point name as declared by DccPermissions (e.g. artifact.write)';

create unique index uk_role_permission on role_permission (role, permission) where deleted_at is null;
create index ix_role_permission_role on role_permission (role);
