-- ADR 0005 §D7: platform-level reference cases ("指导性案例").
--
-- The platform administrator authors one guidance example per feature; a tenant administrator
-- may adopt it (which creates a *draft* artifact in its own tenant) or ignore it and maintain
-- from scratch. Rows are platform-level: no tenant_id, so the Hibernate tenantFilter does not
-- apply, exactly like `tenant` / `role_assignment`. Retention columns come from BaseEntity.

CREATE TABLE reference_case (
    id              bigint generated by default as identity PRIMARY KEY,
    feature         varchar(32)  NOT NULL,
    code            varchar(128) NOT NULL,
    name            varchar(255) NOT NULL,
    description     varchar(1024),
    content         text         NOT NULL,
    case_version    varchar(32)  NOT NULL,
    enabled         boolean      NOT NULL DEFAULT true,
    created_at      timestamp with time zone NOT NULL,
    updated_at      timestamp with time zone NOT NULL,
    deleted_at      timestamp with time zone,
    deleted_by      varchar(128),
    deletion_reason varchar(512)
);

COMMENT ON TABLE reference_case IS
    'Platform-authored guidance examples (ADR 0005); adopted into a tenant as drafts';
COMMENT ON COLUMN reference_case.feature IS
    'DATA_STANDARD | TABLE_STRUCTURE | INTERFACE | INTERFACE_TEMPLATE | SKELETON';
COMMENT ON COLUMN reference_case.content IS
    'Feature payload: the artifact content JSON, or the environment/application skeleton for SKELETON';

-- live-uniqueness of (feature, code): a logically deleted case releases its code, like every other
-- retained row in this schema
CREATE UNIQUE INDEX uk_reference_case_feature_code
    ON reference_case (feature, code)
    WHERE deleted_at IS NULL;
CREATE INDEX ix_reference_case_feature ON reference_case (feature);