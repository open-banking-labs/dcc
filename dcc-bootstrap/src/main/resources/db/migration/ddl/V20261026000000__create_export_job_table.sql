-- Asynchronous, S3-backed Excel export queue for data standards.
--
-- Operational bookkeeping, not a business record: this table deliberately has no
-- retention columns and is not audited (see ExportJob). Rows are written when the
-- console requests an export, claimed by a worker with `for update skip locked`, and
-- kept after completion so the task status remains queryable.

CREATE TABLE export_job (
    id              bigint generated by default as identity PRIMARY KEY,
    tenant_id       varchar(64)  NOT NULL,
    requested_by    varchar(128),
    status          varchar(16)  NOT NULL,
    environment_id  bigint       NOT NULL,
    application_id  bigint       NOT NULL,
    keyword         varchar(128),
    category        varchar(64),
    status_filter   varchar(32),
    standard_ids    varchar(2048),
    object_key      varchar(512),
    file_name       varchar(256),
    row_count       integer,
    error_message   varchar(1024),
    expires_at      timestamp with time zone,
    started_at      timestamp with time zone,
    finished_at     timestamp with time zone,
    created_at      timestamp with time zone NOT NULL,
    updated_at      timestamp with time zone NOT NULL
);

COMMENT ON TABLE export_job IS
    'Asynchronous Excel export tasks; status PENDING/RUNNING/READY/FAILED/EXPIRED';
COMMENT ON COLUMN export_job.status_filter IS
    'Data-standard status filter; null means all statuses';
COMMENT ON COLUMN export_job.standard_ids IS
    'Comma-separated selected standard ids; null means the filter fields are used';

-- Status polling and expiry cleanup are tenant-scoped/status-scoped lookups.
CREATE INDEX ix_export_job_tenant_status ON export_job (tenant_id, status);

-- The worker claims the oldest pending row; the partial index keeps that scan tiny.
CREATE INDEX ix_export_job_pending ON export_job (status, id) WHERE status = 'PENDING';

-- One active export per tenant at a time, enforced by the database so two
-- application instances cannot both accept a request. The index frees the tenant
-- as soon as the job reaches READY/FAILED/EXPIRED.
CREATE UNIQUE INDEX uk_export_job_active_tenant
    ON export_job (tenant_id)
    WHERE status IN ('PENDING', 'RUNNING');
