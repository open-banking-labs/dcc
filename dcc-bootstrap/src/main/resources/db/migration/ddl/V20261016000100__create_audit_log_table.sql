-- Append-only audit trail: one row per create / update / logical delete, with who, why
-- and the before/after images (JSON text). Written by AuditListener -> AuditRecorder just
-- before the surrounding transaction commits, so an entry and the change it describes are
-- committed atomically.
--
-- The trail is immutable by design: nothing updates or deletes these rows (revoke UPDATE
-- and DELETE from the application role in production). `hash` chains to `previous_hash`
-- (the previous entry for the same entity) so a tampered or removed entry breaks the chain.

CREATE TABLE audit_log (
    id             bigint generated by default as identity PRIMARY KEY,
    tenant_id      varchar(64),
    entity_type    varchar(64)  NOT NULL,
    entity_id      bigint       NOT NULL,
    entity_code    varchar(128),
    action         varchar(32)  NOT NULL,
    actor          varchar(128) NOT NULL,
    reason         varchar(512),
    changed_fields text,
    before_state   text,
    after_state    text,
    trace_id       varchar(64),
    previous_hash  varchar(71),
    hash           varchar(71)  NOT NULL,
    occurred_at    timestamp with time zone NOT NULL
);

CREATE INDEX ix_audit_entity ON audit_log (entity_type, entity_id, id);
CREATE INDEX ix_audit_tenant_time ON audit_log (tenant_id, occurred_at);
CREATE INDEX ix_audit_tenant_actor ON audit_log (tenant_id, actor);
